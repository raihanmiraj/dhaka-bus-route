export function stopCoordinate(name: string): LatLng | null {
  const id = slugify(name);
  const key = aliases[id] ?? id;
  if (known[key]) return known[key];
  // Fuzzy: try stripping parenthetical suffixes already handled by slugify.
  const compact = normalize(name).replace(/\s+/g, "-");
  return known[aliases[compact] ?? compact] ?? null;
}

export function routeMapPoints(stops: string[]) {
  return stops
    .map((name, index) => {
      const point = stopCoordinate(name);
      return point ? { name, index, ...point } : null;
    })
    .filter((p): p is { name: string; index: number; lat: number; lng: number } => !!p);
}
